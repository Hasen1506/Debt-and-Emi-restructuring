/**
 * Calendar reminders from the loans on file. Built in the browser from
 * the current loans, so a re-download follows a date change. The UID is
 * stable per loan, so a calendar that replaces by UID updates the old
 * reminder instead of adding a second one.
 */
import type { LoanPayload } from './api';
import { loanLabel } from './loan-types';

export interface CalendarEvent {
  uid: string;
  title: string;
  date: string;
  /** Months the reminder repeats, including the first. 1 = one day. */
  count: number;
  description: string;
}

const stamp = (iso: string) => iso.replace(/-/g, '');

function addMonths(ym: string, n: number, day: number): string {
  const [y, m] = ym.split('-').map(Number);
  const k = y * 12 + (m - 1) + n;
  const year = Math.floor(k / 12);
  const month = (k % 12) + 1;
  const last = new Date(Date.UTC(year, month, 0)).getUTCDate();
  const d = Math.min(Math.max(1, day), last);
  return `${year}-${String(month).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
}

/** One event per loan that has a date to remind. Pay-whenever with no
 *  due date is skipped. `todayMonth` is 'YYYY-MM'. */
export function eventsForLoans(loans: LoanPayload[], todayMonth: string): CalendarEvent[] {
  const out: CalendarEvent[] = [];
  loans.forEach((l, i) => {
    if (!(Number(l.outstanding) > 0)) return;
    const id = l.id || `i${i}`;
    const name = loanLabel(l);
    const day = l.due_day && l.due_day >= 1 && l.due_day <= 31 ? l.due_day : 5;
    if (l.loan_type === 'people_loan' && l.people_repay === 'whenever' && !l.people_due) return;
    if (l.repayment === 'bullet' || l.people_repay === 'lump') {
      const due = l.people_due;
      const date = due && /^\d{4}-\d{2}$/.test(due) ? addMonths(due, 0, day) : l.tenure_months_remaining > 0 ? addMonths(todayMonth, l.tenure_months_remaining, day) : '';
      if (!date) return;
      out.push({
        uid: `rightdue-${id}-lump@rightdue.app`,
        title: `${name} due`,
        date,
        count: 1,
        description: 'Lump sum due. Generated by RightDue from your loans.',
      });
      return;
    }
    if (!(Number(l.scheduled_emi) > 0)) return;
    const count = Math.max(1, Math.min(600, l.tenure_months_remaining || 1));
    out.push({
      uid: `rightdue-${id}-emi@rightdue.app`,
      title: `${name} payment`,
      date: addMonths(todayMonth, 0, day),
      count,
      description: 'Monthly payment. Generated by RightDue from your loans. Download again after a date changes.',
    });
  });
  return out;
}

function vevent(e: CalendarEvent): string {
  const recur = e.count > 1 ? `\nRRULE:FREQ=MONTHLY;COUNT=${e.count}` : '';
  return [
    'BEGIN:VEVENT',
    `UID:${e.uid}`,
    `DTSTAMP:${stamp(e.date)}T000000Z`,
    `DTSTART;VALUE=DATE:${stamp(e.date)}`,
    `SUMMARY:${e.title.replace(/[\n,;]/g, ' ')}`,
    `DESCRIPTION:${e.description}`,
    recur,
    'END:VEVENT',
  ].filter(Boolean).join('\n');
}

export function icsFor(events: CalendarEvent[]): string {
  return ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//RightDue//Loans//EN', 'CALSCALE:GREGORIAN', ...events.map(vevent), 'END:VCALENDAR'].join('\n');
}

/** Google Calendar template for one event. All-day, monthly when it repeats. */
export function googleCalendarUrl(e: CalendarEvent): string {
  const start = stamp(e.date);
  const [y, m, d] = e.date.split('-').map(Number);
  const end = new Date(Date.UTC(y, m - 1, d + 1)).toISOString().slice(0, 10).replace(/-/g, '');
  const params = new URLSearchParams({
    action: 'TEMPLATE',
    text: e.title,
    dates: `${start}/${end}`,
    details: e.description,
  });
  if (e.count > 1) params.set('recur', `RRULE:FREQ=MONTHLY;COUNT=${e.count}`);
  return `https://calendar.google.com/calendar/render?${params.toString()}`;
}

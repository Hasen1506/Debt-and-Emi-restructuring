"""What the repo's lines actually are, by kind (E14/E21, Audit 80).

    python scripts/size_report.py            # table of tracked lines by category
    python scripts/size_report.py --json     # same, machine-readable
    python scripts/size_report.py --check    # CI budget: fail on a new file over
                                             # MAX_FILE_LINES or a grandfathered one growing

"Lines" means newline count of tracked files (git ls-files), the same number
`wc -l` gives, so it matches the audit's 110k figure for production code.
Binary files (icons, fonts, PDFs, gz) are counted as bytes only.

The budget (--check) is deliberately simple so a founder can read it:
- no production source file (web/src, engine, api; not tests, not data) may be
  over MAX_FILE_LINES lines, except the files listed in
  scripts/size_budget.json "grandfathered", which may only shrink;
- the production-line total may not grow by more than PROD_GROWTH_PCT over the
  committed baseline in the same file. Raise the baseline in the PR that
  deletes something, or explain the growth in the PR and bump it on purpose.
"""
from __future__ import annotations

import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUDGET_FILE = ROOT / "scripts" / "size_budget.json"
MAX_FILE_LINES = 1500
PROD_GROWTH_PCT = 1.0

BINARY_EXT = {".ico", ".png", ".jpg", ".jpeg", ".woff", ".woff2", ".pdf", ".gz", ".zip"}
CODE_EXT = {".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".css"}

# First match wins. (prefix or predicate, category)
def categorize(path: str) -> str:
    p = path
    ext = Path(p).suffix.lower()
    if ext in BINARY_EXT:
        return "binary assets (icons, fonts, PDFs, gz)"
    if p.endswith("package-lock.json"):
        return "lockfile (generated by npm)"
    if p.startswith("engine/tests/fixtures/") or p.startswith("api/tests/fixtures/"):
        if ext == ".json":
            return "generated test fixtures (JSON)"
        return "test fixtures (other)"
    if p.startswith(("engine/tests/", "api/tests/")):
        return "tests: Python"
    if p.startswith("web/tests/"):
        return "tests: web node --test"
    if p.startswith("web/e2e/") or p.startswith("e2e/"):
        return "tests: Playwright E2E"
    if p.startswith("docs/archive/") or p.startswith("docs/history/") or p.startswith("docs/planning/"):
        return "docs: planning/history archive"
    if p.startswith("design/"):
        return "design mockups (not shipped)"
    if p.startswith("docs/") or (("/" not in p) and ext == ".md"):
        return "docs: current"
    if p.startswith("scripts/") or p.startswith("web/scripts/"):
        return "scripts (generators, one-off audits)"
    if p.startswith(("web/src/", "engine/", "api/")) and ext == ".json":
        return "data snapshots (JSON in source tree)"
    if p.startswith("web/public/"):
        return "web/public (static pages, svg)"
    if p.startswith("web/src/") and ext in CODE_EXT:
        return "PROD: web/src"
    if p.startswith("engine/") and ext in CODE_EXT:
        return "PROD: engine"
    if p.startswith("api/") and ext in CODE_EXT:
        return "PROD: api"
    return "config, CI, deploy, misc"


def is_prod(cat: str) -> bool:
    return cat.startswith("PROD:")


def tracked_files() -> list[str]:
    out = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT)
    return [f for f in out.decode().split("\0") if f]


def measure() -> dict:
    cats: dict[str, dict] = defaultdict(lambda: {"files": 0, "lines": 0, "bytes": 0})
    per_file: dict[str, int] = {}
    for f in tracked_files():
        fp = ROOT / f
        if not fp.is_file():
            continue
        data = fp.read_bytes()
        cat = categorize(f)
        binary = Path(f).suffix.lower() in BINARY_EXT
        lines = 0 if binary else data.count(b"\n")
        c = cats[cat]
        c["files"] += 1
        c["lines"] += lines
        c["bytes"] += len(data)
        if is_prod(cat):
            per_file[f] = lines
    total = {k: sum(c[k] for c in cats.values()) for k in ("files", "lines", "bytes")}
    prod = sum(per_file.values())
    return {"categories": dict(cats), "total": total, "prod_lines": prod, "prod_files": per_file}


def check(m: dict) -> int:
    budget = json.loads(BUDGET_FILE.read_text(encoding="utf-8"))
    grand: dict[str, int] = budget.get("grandfathered", {})
    max_lines = budget.get("max_file_lines", MAX_FILE_LINES)
    errors: list[str] = []
    for f, n in sorted(m["prod_files"].items()):
        if f in grand:
            if n > grand[f]:
                errors.append(f"{f}: {n} lines, grandfathered at {grand[f]} and may only shrink")
        elif n > max_lines:
            errors.append(f"{f}: {n} lines, over the {max_lines}-line limit (split it)")
    base = budget["prod_lines_baseline"]
    allowed = int(base * (1 + budget.get("prod_growth_pct", PROD_GROWTH_PCT) / 100))
    if m["prod_lines"] > allowed:
        errors.append(
            f"production lines {m['prod_lines']} > {allowed} ({base} baseline + "
            f"{budget.get('prod_growth_pct', PROD_GROWTH_PCT)}%). Delete something, or raise "
            "prod_lines_baseline in scripts/size_budget.json and say why in the PR."
        )
    shrunk = [f for f, cap in grand.items() if m["prod_files"].get(f, 0) < cap]
    print(f"production lines: {m['prod_lines']} (baseline {base}, ceiling {allowed})")
    if shrunk:
        print("grandfathered files that shrank (lower their cap in size_budget.json): " + ", ".join(shrunk))
    for e in errors:
        print(f"::error::{e}")
    return 1 if errors else 0


def main(argv: list[str]) -> int:
    m = measure()
    if "--check" in argv:
        return check(m)
    if "--json" in argv:
        print(json.dumps({k: v for k, v in m.items() if k != "prod_files"}, indent=2, sort_keys=True))
        return 0
    rows = sorted(m["categories"].items(), key=lambda kv: -kv[1]["lines"])
    print(f"{'category':48} {'files':>6} {'lines':>8} {'KB':>8}")
    for cat, c in rows:
        print(f"{cat:48} {c['files']:>6} {c['lines']:>8} {c['bytes'] // 1024:>8}")
    t = m["total"]
    print(f"{'TOTAL':48} {t['files']:>6} {t['lines']:>8} {t['bytes'] // 1024:>8}")
    print(f"production code lines (web/src + engine + api, no tests/data): {m['prod_lines']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

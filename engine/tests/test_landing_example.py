"""The landing page's example figures come from the engine (sprint G10, grill #44).

web/src/lib/landing-example.json is generated by scripts/landing_example.py and
web/public/welcome.html carries its generated blocks. If the engine changes
(e.g. the card minimum formula), re-run:

    python scripts/landing_example.py --write
    python scripts/landing_example.py --html
"""
from __future__ import annotations

import importlib.util
import json
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("landing_example", ROOT / "scripts" / "landing_example.py")
le = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(le)  # type: ignore[union-attr]

SAVED = json.loads(le.OUT.read_text())
FRESH = le.figures()


def test_json_matches_the_engine():
    assert SAVED == FRESH, "re-run: python scripts/landing_example.py --write --html"


def test_welcome_html_matches_the_json():
    html = le.WELCOME.read_text()
    assert le.render_html(html, SAVED) == html, "re-run: python scripts/landing_example.py --html"


def test_baseline_is_smallest_first_with_the_same_budget():
    for c in ("IN", "US"):
        x = SAVED[c]
        # The plan never does worse than Snowball on the same money.
        assert x["vs_smallest_first"]["months_sooner"] >= 0
        assert Decimal(x["vs_smallest_first"]["interest_saved"]) >= 0
        # Month 1 pays the whole budget, and never less than what's due.
        first = {r["loan"]: Decimal(r["payment"]) for r in x["plan"]["first_month"]}
        due = {r["loan"]: Decimal(r["payment"]) for r in x["plan"]["first_month_due"]}
        assert sum(first.values()) == Decimal(x["budget"])
        assert all(first[k] >= due[k] for k in due)


def test_only_whats_due_is_a_ceiling_not_faster():
    for c in ("IN", "US"):
        x = SAVED[c]
        m = x["vs_only_whats_due"]["debt_free_month"]
        assert m is None or m > x["plan"]["debt_free_month"]


def test_payoffs_are_in_order_and_last_is_debt_free():
    for c in ("IN", "US"):
        p = SAVED[c]["plan"]
        months = [r["month"] for r in p["payoffs"]]
        assert all(m is not None for m in months)
        assert max(months) == p["debt_free_month"]
        assert p["debt_free"] == le._month_label(p["debt_free_month"])


def test_extra_goes_to_the_card_first():
    # Avalanche: month 1's extra over what's due lands on the credit card,
    # the dearest loan in both examples.
    for c in ("IN", "US"):
        p = SAVED[c]["plan"]
        due = {r["loan"]: Decimal(r["payment"]) for r in p["first_month_due"]}
        extra = {r["loan"]: Decimal(r["payment"]) - due[r["loan"]] for r in p["first_month"]}
        assert max(extra, key=extra.get) == "Credit card"
        assert sum(v for k, v in extra.items() if k != "Credit card") == 0


def test_chart_labels_never_collide():
    """Live test 2026-10-13: the milestone labels overlapped, a leader ran
    through another label, and the due note sat far from its line. Every
    label now stays inside the plot, clear of both lines, of every other
    label and of every other leader; its leader starts at its own square."""
    for c in ("IN", "US"):
        ch = SAVED[c]["chart"]
        lay = le.layout_chart(ch, le.chart_labels(ch), le.money(c, ch["due_left_at_edge"]))
        boxes = [o["box"] for o in lay["marks"]] + [lay["final"]["box"], lay["note"]["box"]]
        for b in boxes:
            assert b[0] >= le.PLOT_X0 - 0.5 and b[2] <= le.PLOT_X1 + 0.5, (c, b)
        for i, a in enumerate(boxes):
            for b in boxes[i + 1:]:
                assert not le._overlap(a, b), (c, a, b)
        plan, due = le._pts(ch["plan_path"]), le._pts(ch["due_path"])
        for b in boxes:
            for line in (plan, due):
                assert not any(le._hit(p, q, b) for p, q in zip(line, line[1:])), (c, b)
        for o in lay["marks"]:
            (lx, _), _ = o["leader"]
            assert any(abs(m["x"] - lx) < 0.01 for m in o["cluster"]), (c, o["texts"])
            assert o["box"][0] - 6 <= lx <= o["box"][2] + 6, (c, o["texts"])  # text sits at its marker
            for b in boxes:
                if b != o["box"]:
                    assert not le._hit(*o["leader"], b), (c, o["texts"], b)
        # Markers less than MERGE_DX apart share one leader and one label.
        xs = sorted(m["x"] for m in ch["markers"][:-1])
        assert len(lay["marks"]) == 1 + sum(1 for a, b in zip(xs, xs[1:]) if b - a >= le.MERGE_DX)
        # The due note ends at the dashed line's last point, just under it.
        ex, ey = le._pts(ch["due_path"])[-1]
        assert abs(lay["note"]["x"] - ex) <= 10 and 0 < lay["note"]["y"] - ey <= 24
